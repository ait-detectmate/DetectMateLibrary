"""The layout rules of tests/ (see tests/README.md), checked instead of
trusted.

- tests/ holds only the level folders, the shared support code and the
  test data;
- every test directory is a package (file names such as test_parser.py
  repeat);
- tests/unit/ mirrors src/detectmatelibrary/: every unit test file names
  the module it tests (test_<module>.py or test_<module>_<topic>.py), and
  every source module has such a file or an entry with a reason in
  NO_UNIT_TEST_FILE below;
- every test module starts with a docstring that says what it covers.
"""
import ast
from pathlib import Path

import pytest

TESTS = Path(__file__).resolve().parent
UNIT = TESTS / "unit"
SRC = TESTS.parent / "src" / "detectmatelibrary"

TOP_LEVEL = {
    "__init__.py", "conftest.py", "compose.yaml", "test_layout.py", "README.md",
    "support", "test_data", "unit", "contract", "integration", "e2e",
}

# Source modules without their own unit test file, and why. A module leaves
# this list as soon as tests/unit/ gets a file for it.
NO_UNIT_TEST_FILE = {
    # nothing to test on its own
    "__init__.py": "package re-exports only (checked by importing the public names)",
    "constants.py": "constants only",
    "metadata.py": "package metadata only",
    "schemas/protobuf/schemas_pb2.py": "generated by protoc",
    "utils/deep_learning/imodel.py": "abstract base class of the deep-learning models",
    # tested at another level
    "schemas/connectors/mongos.py": "needs a real MongoDB: tests/integration/test_mongo_connector.py",
    "schemas/connectors/redis.py": "needs a real Redis: tests/integration/test_redis_connector.py",
    "detectors/deeplog_detector.py": "DeepLearningDetector config: contract, e2e C3",
    "detectors/logbert_detector.py": "DeepLearningDetector config: contract, e2e C3",
    # out of scope
    "parsers/logbatcher/engine": "vendored LogBatcher engine (MIT), needs an LLM; out of scope",
    "tools/workspace/templates": "copied into generated workspaces; run by tests/e2e/test_workspace_cli.py",
}

# Unit test files that don't follow the mirror rule yet, and why.
NOT_MIRRORED: dict[str, str] = {}


def _src_modules() -> list[Path]:
    return sorted(p for p in SRC.rglob("*.py") if "__pycache__" not in p.parts)


def _allowed_without_test(module: Path) -> bool:
    rel = module.relative_to(SRC).as_posix()
    if rel in NO_UNIT_TEST_FILE or any(rel.startswith(prefix + "/") for prefix in NO_UNIT_TEST_FILE):
        return True
    return module.name == "__init__.py" and _only_reexports(module)


_REEXPORT_NODES = (ast.Import, ast.ImportFrom, ast.Expr, ast.Assign, ast.AnnAssign, ast.FunctionDef, ast.Pass)


def _only_reexports(module: Path) -> bool:
    """A package __init__ that only imports and lists names (optional imports
    guarded by try/if, a lazy __getattr__ allowed), but defines no class."""
    def plain(nodes: list[ast.stmt]) -> bool:
        for node in nodes:
            if isinstance(node, (ast.Try, ast.If)):
                handlers = [h for t in getattr(node, "handlers", []) for h in t.body]
                if not plain(node.body + node.orelse + handlers + getattr(node, "finalbody", [])):
                    return False
            elif not isinstance(node, _REEXPORT_NODES):
                return False
        return True

    return plain(ast.parse(module.read_text()).body)


def _modules_tested_by(test_file: Path) -> list[Path]:
    """Source modules a unit test file names: tests/unit/<dir>/test_<name>[_<topic>].py ->
    src/detectmatelibrary/<dir>/<name>.py, _<name>.py, or <name>/__init__.py."""
    src_dir = SRC / test_file.parent.relative_to(UNIT)
    stem = test_file.stem.removeprefix("test_")
    found = []
    for module in src_dir.glob("*.py"):
        name = (src_dir.name if module.stem == "__init__" else module.stem).lstrip("_")
        if stem == name or stem.startswith(name + "_"):
            found.append(module)
    return found


def _unit_test_files() -> list[Path]:
    return sorted(UNIT.rglob("test_*.py"))


def test_only_known_entries_at_the_top_of_tests() -> None:
    unexpected = {p.name for p in TESTS.iterdir() if p.name != "__pycache__"} - TOP_LEVEL
    assert not unexpected, f"put these into unit/, contract/, integration/ or e2e/: {sorted(unexpected)}"


def test_every_test_directory_is_a_package() -> None:
    missing = [
        d.relative_to(TESTS).as_posix()
        for d in [TESTS, *TESTS.rglob("*")]
        if d.is_dir() and "__pycache__" not in d.parts and "test_data" not in d.relative_to(TESTS).parts
        and not (d / "__init__.py").exists()
    ]
    assert not missing, f"add an __init__.py to: {missing}"


@pytest.mark.parametrize("test_file", _unit_test_files(), ids=lambda p: p.relative_to(UNIT).as_posix())
def test_unit_test_file_names_its_source_module(test_file: Path) -> None:
    if test_file.relative_to(UNIT).as_posix() in NOT_MIRRORED:
        return
    assert _modules_tested_by(test_file), (
        f"{test_file.relative_to(TESTS)} matches no module in "
        f"{(SRC / test_file.parent.relative_to(UNIT)).relative_to(SRC.parent)}; name it test_<module>.py"
    )


def test_every_source_module_has_a_unit_test_file() -> None:
    tested = {module for test_file in _unit_test_files() for module in _modules_tested_by(test_file)}
    untested = [
        m.relative_to(SRC).as_posix()
        for m in _src_modules()
        if m not in tested and not _allowed_without_test(m)
    ]
    assert not untested, (
        f"no tests/unit/ file for {untested}; "
        "add one, or a reason to NO_UNIT_TEST_FILE in tests/test_layout.py"
    )


def test_no_stale_entries_in_the_lists() -> None:
    tested = {module for test_file in _unit_test_files() for module in _modules_tested_by(test_file)}
    stale = [
        rel for rel in NO_UNIT_TEST_FILE
        if rel != "__init__.py" and (SRC / rel).is_file() and (SRC / rel) in tested
    ]
    missing = [rel for rel in NO_UNIT_TEST_FILE if rel != "__init__.py" and not (SRC / rel).exists()]
    assert not stale, f"these now have a unit test file; remove them from NO_UNIT_TEST_FILE: {stale}"
    assert not missing, f"these no longer exist; remove them from NO_UNIT_TEST_FILE: {missing}"


@pytest.mark.parametrize(
    "test_file", sorted(TESTS.rglob("test_*.py")), ids=lambda p: p.relative_to(TESTS).as_posix()
)
def test_every_test_module_has_a_docstring(test_file: Path) -> None:
    docstring = ast.get_docstring(ast.parse(test_file.read_text()))
    assert docstring, "say in a module docstring what this file covers"
